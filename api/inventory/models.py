from django.db import models


class Tenant(models.Model):
    """A customer. Every row in this app belongs to exactly one tenant."""

    name = models.CharField(max_length=120, help_text='Company name, for display only.')

    def __str__(self) -> str:
        return self.name


class Device(models.Model):
    """A machine discovered on a tenant's network, or reported by the agent installed on it."""

    tenant = models.ForeignKey(
        Tenant, on_delete=models.CASCADE, related_name='devices', help_text='The customer this device belongs to.'
    )
    hostname = models.CharField(max_length=255, help_text='Hostname as last reported or discovered.')
    ip_address = models.CharField(max_length=45, help_text='Last known IPv4 or IPv6 address, as text.')

    agent_guid = models.CharField(
        max_length=64,
        null=True,
        blank=True,
        help_text='Set when an agent is installed on the device. Generated by the agent at install '
        'time, unique only within a tenant.',
    )
    os_name = models.CharField(max_length=64, blank=True, help_text='Operating system name, e.g. Ubuntu.')
    os_version = models.CharField(max_length=64, blank=True, help_text='Operating system version, e.g. 22.04.')
    last_checkin = models.DateTimeField(
        null=True, blank=True, help_text='When the agent last reported, as stamped by the agent itself.'
    )

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['tenant', 'agent_guid'], name='unique_agent_guid_per_tenant'),
        ]

    def __str__(self) -> str:
        return self.hostname


class Application(models.Model):
    """An application or service found running on a device."""

    class StatusType(models.TextChoices):
        ONLINE = 'online', 'Online'
        OFFLINE = 'offline', 'Offline'

    class RiskLevelType(models.TextChoices):
        CRITICAL = 'critical', 'Critical'
        HIGH = 'high', 'High'
        MEDIUM = 'medium', 'Medium'
        LOW = 'low', 'Low'
        NONE = 'none', 'None'

    tenant = models.ForeignKey(
        Tenant,
        on_delete=models.CASCADE,
        related_name='applications',
        help_text='The customer this application belongs to. Always the same as its device\'s tenant.',
    )
    device = models.ForeignKey(
        Device,
        on_delete=models.CASCADE,
        related_name='applications',
        help_text='The device this application runs on. The related_name gives every Device a '
        '`device.applications` manager over its applications.',
    )
    name = models.CharField(max_length=255, help_text='Package or product name as the agent reports it, e.g. nginx.')
    version = models.CharField(max_length=64, blank=True, help_text='Installed version as reported, e.g. 1.18.0.')
    cpe = models.CharField(
        max_length=255,
        blank=True,
        help_text='The CPE Threat Intel resolved for this name and version, if any. Empty until scanned.',
    )
    status = models.CharField(
        max_length=16,
        choices=StatusType.choices,
        default=StatusType.ONLINE,
        help_text='Whether the application was present the last time its device reported.',
    )
    risk_level = models.CharField(
        max_length=16,
        choices=RiskLevelType.choices,
        default=RiskLevelType.NONE,
        help_text='Derived from the highest CVSS score among the open CVEs of this application.',
    )
    discovered_on = models.DateTimeField(help_text='When this application was first seen on this device.')
    last_seen = models.DateTimeField(help_text='When this application was last reported as present.')
    last_scanned = models.DateTimeField(
        null=True, blank=True, help_text='When this application was last checked against Threat Intel, if ever.'
    )

    class Meta:
        indexes = [models.Index(fields=['tenant', '-discovered_on'])]

    def __str__(self) -> str:
        return self.name


class Vulnerability(models.Model):
    """A CVE, as last described by Threat Intel.

    This is a global catalogue: a CVE is the same thing for every tenant, so the
    table has no tenant column and is shared across them.
    """

    cve = models.CharField(max_length=32, primary_key=True, help_text='The CVE id, e.g. CVE-2021-23017.')
    summary = models.TextField(blank=True, help_text='The English description from the CVE record.')
    cvss_base = models.FloatField(
        null=True, blank=True, help_text='CVSS v3 base score, 0.0 to 10.0. Null when Threat Intel has no score.'
    )
    cvss_severity = models.CharField(
        max_length=16, blank=True, help_text='CVSS v3 severity label as served: LOW, MEDIUM, HIGH or CRITICAL.'
    )
    is_weaponized = models.BooleanField(default=False, help_text='True when a public exploit is known to exist.')
    last_updated = models.DateTimeField(
        help_text='When the row was last refreshed from Threat Intel. Drives the cache TTL.'
    )

    class Meta:
        verbose_name_plural = 'vulnerabilities'

    def __str__(self) -> str:
        return self.cve


class ApplicationVulnerability(models.Model):
    """A CVE Threat Intel reported for one application, and whether it is still there."""

    class State(models.TextChoices):
        OPEN = 'open', 'Open'
        FIXED = 'fixed', 'Fixed'

    tenant = models.ForeignKey(
        Tenant,
        on_delete=models.CASCADE,
        related_name='application_vulnerabilities',
        help_text='The customer this finding belongs to. Always the same as the application\'s tenant.',
    )
    application = models.ForeignKey(
        Application,
        on_delete=models.CASCADE,
        related_name='vulnerabilities',
        help_text='The affected application. Reachable the other way as `application.vulnerabilities`.',
    )
    vulnerability = models.ForeignKey(
        Vulnerability, on_delete=models.CASCADE, related_name='applications', help_text='The CVE in question.'
    )
    state = models.CharField(
        max_length=8,
        choices=State.choices,
        default=State.OPEN,
        help_text='Open while Threat Intel keeps reporting the CVE for this application; fixed once it stops.',
    )
    discovered_on = models.DateTimeField(help_text='When this CVE was first reported for this application.')
    last_seen = models.DateTimeField(help_text='When this CVE was last reported for this application.')

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['application', 'vulnerability'], name='unique_cve_per_application'),
        ]
        indexes = [models.Index(fields=['tenant', 'state'])]

    def __str__(self) -> str:
        return f'{self.application_id}:{self.vulnerability_id}'
