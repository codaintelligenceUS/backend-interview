from django.db import models


class Tenant(models.Model):
    """A customer. Every row in this app belongs to exactly one tenant."""

    name = models.CharField(max_length=120)

    def __str__(self) -> str:
        return self.name


class Device(models.Model):
    """A machine discovered on a tenant's network, or reported by the agent installed on it."""

    tenant = models.ForeignKey(Tenant, on_delete=models.CASCADE, related_name='devices')
    hostname = models.CharField(max_length=255)
    ip_address = models.CharField(max_length=45)

    agent_guid = models.CharField(
        max_length=64,
        null=True,
        blank=True,
        help_text='Set when an agent is installed on the device. Generated by the agent at install '
        'time, unique only within a tenant.',
    )
    os_name = models.CharField(max_length=64, blank=True)
    os_version = models.CharField(max_length=64, blank=True)
    last_checkin = models.DateTimeField(
        null=True, blank=True, help_text='When the agent last reported, as stamped by the agent itself.'
    )

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['tenant', 'agent_guid'], name='unique_agent_guid_per_tenant'),
        ]

    def __str__(self) -> str:
        return self.hostname


class Application(models.Model):
    """An application/service found running on a device."""

    class StatusType(models.TextChoices):
        ONLINE = 'online', 'Online'
        OFFLINE = 'offline', 'Offline'
        NOT_SEEN = 'not_seen', 'Not Seen on Last Scan'
        DECOMMISSIONED = 'decommissioned', 'Decommissioned'

    class RiskLevelType(models.TextChoices):
        CRITICAL = 'critical', 'Critical'
        HIGH = 'high', 'High'
        MEDIUM = 'medium', 'Medium'
        LOW = 'low', 'Low'
        NONE = 'none', 'None'

    tenant = models.ForeignKey(Tenant, on_delete=models.CASCADE, related_name='applications')
    device = models.ForeignKey(
        Device,
        on_delete=models.CASCADE,
        related_name='applications',
        help_text='The device this application runs on. The related_name gives every Device a '
        '`device.applications` manager over its applications.',
    )
    name = models.CharField(max_length=255)
    version = models.CharField(max_length=64, blank=True)
    cpe = models.CharField(
        max_length=255,
        blank=True,
        help_text='The CPE Threat Intel resolved for this name and version, if any. Empty until scanned.',
    )
    status = models.CharField(max_length=16, choices=StatusType.choices, default=StatusType.ONLINE)
    risk_level = models.CharField(max_length=16, choices=RiskLevelType.choices, default=RiskLevelType.NONE)
    is_scanned = models.BooleanField(default=False)
    discovered_on = models.DateTimeField()
    last_seen = models.DateTimeField()
    last_scanned = models.DateTimeField(null=True, blank=True)

    class Meta:
        indexes = [models.Index(fields=['tenant', '-discovered_on'])]

    def __str__(self) -> str:
        return self.name


class Vulnerability(models.Model):
    """A CVE, as last described by Threat Intel.

    This is a global catalogue: a CVE is the same thing for every tenant, so the
    table has no tenant column and is shared across them.
    """

    cve = models.CharField(max_length=32, primary_key=True)
    summary = models.TextField(blank=True)
    cvss_base = models.FloatField(null=True, blank=True)
    cvss_severity = models.CharField(max_length=16, blank=True)
    is_weaponized = models.BooleanField(default=False)
    last_updated = models.DateTimeField(
        help_text='When the row was last refreshed from Threat Intel. Drives the cache TTL.'
    )

    class Meta:
        verbose_name_plural = 'vulnerabilities'

    def __str__(self) -> str:
        return self.cve


class ApplicationVulnerability(models.Model):
    """A CVE Threat Intel reported for one application, and whether it is still there."""

    class State(models.TextChoices):
        OPEN = 'open', 'Open'
        FIXED = 'fixed', 'Fixed'

    tenant = models.ForeignKey(Tenant, on_delete=models.CASCADE, related_name='application_vulnerabilities')
    application = models.ForeignKey(Application, on_delete=models.CASCADE, related_name='vulnerabilities')
    vulnerability = models.ForeignKey(Vulnerability, on_delete=models.CASCADE, related_name='applications')
    state = models.CharField(max_length=8, choices=State.choices, default=State.OPEN)
    discovered_on = models.DateTimeField()
    last_seen = models.DateTimeField()

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['application', 'vulnerability'], name='unique_cve_per_application'),
        ]
        indexes = [models.Index(fields=['tenant', 'state'])]

    def __str__(self) -> str:
        return f'{self.application_id}:{self.vulnerability_id}'
